def get_classification_name(dm_code: str) -> str:
    """4桁分類コードからレイヤ名用の名称を返す。

    コード表にある場合: データ名を返す（例: "道路縁（街区線）"）
    未分類(00)の場合: グループ名_未分類を返す（例: "道路_未分類"）
    コード表にない場合: コード4桁をそのまま返す（例: "2199"）
    """
    layer_code = dm_code[:2]
    data_code = dm_code[2:]

    group = CLASSIFICATIONS.get(layer_code)
    if group is None:
        return dm_code

    data_name = group.get(data_code)
    if data_name is None:
        return dm_code

    if data_code == "00":
        return f"{group['name']}_{data_name}"

    return data_name
